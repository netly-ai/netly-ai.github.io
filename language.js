  const readPreference = () => {
    const override = new URLSearchParams(location.search).get('lang');
    if (override === 'np' || override === 'en') return override;
    try { return localStorage.getItem('netly-language') === 'np' ? 'np' : 'en'; }
    catch (_) { return 'en'; }
  };

  function translated(value, language) {
    if (language === 'np') return np[value] || value;
    return reverse[value] || value;
  }

  function updateContent(language) {
    document.documentElement.lang = language === 'np' ? 'ne' : 'en';
    document.title = language === 'np' ? pageMeta.title : (normalizePath === '/' ? 'Netly AI — More room for what matters' : 'Careers at Netly AI');
    const description = document.querySelector('meta[name="description"]');
    const ogTitle = document.querySelector('meta[property="og:title"]');
    const ogDescription = document.querySelector('meta[property="og:description"]');
    if (description) description.content = language === 'np' ? pageMeta.description : (normalizePath === '/' ? 'Netly AI builds thoughtful technology that helps people and teams make more room for what matters.' : 'Explore current opportunities at Netly AI across AI, software engineering, research, security, design, and business development.');
    if (ogTitle) ogTitle.content = language === 'np' ? pageMeta.ogTitle : (normalizePath === '/' ? 'Netly AI — More room for what matters' : 'Careers at Netly AI');
    if (ogDescription) ogDescription.content = language === 'np' ? pageMeta.ogDescription : (normalizePath === '/' ? 'Human-centered technology, built with care.' : 'Bring your curiosity. Make work matter. Explore eight opportunities at Netly AI.');

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (!node.nodeValue.trim() || node.parentElement.closest('script,style,.language-switch')) continue;
      const current = node.nodeValue;
      const trimmed = current.trim();
      const translatedValue = translated(trimmed, language);
      if (translatedValue !== trimmed) node.nodeValue = current.replace(trimmed, translatedValue);
    }
    document.querySelectorAll('[aria-label],[alt],[title]').forEach((element) => {
      for (const attribute of ['aria-label', 'alt', 'title']) {
        const value = element.getAttribute(attribute);
        if (value) element.setAttribute(attribute, translated(value, language));
      }
    });
    document.querySelectorAll('.language-switch button').forEach((button) => {
      const active = button.dataset.language === language;
      button.setAttribute('aria-pressed', String(active));
      button.setAttribute('aria-label', button.dataset.language === 'en' ? (language === 'np' ? 'अङ्ग्रेजी' : 'English') : 'नेपाली');
    });
    document.querySelectorAll('.language-switch').forEach((group) => group.setAttribute('aria-label', language === 'np' ? 'भाषा' : 'Language'));
    try { localStorage.setItem('netly-language', language); } catch (_) { /* preference remains page-local */ }
  }

  function addSwitcher() {
    document.querySelectorAll('.main-nav').forEach((nav) => {
      if (nav.querySelector('.language-switch')) return;
      const group = document.createElement('div');
      group.className = 'language-switch';
      group.setAttribute('role', 'group');
      group.setAttribute('aria-label', 'Language / भाषा');
      group.innerHTML = '<button type="button" data-language="en" aria-label="English">EN</button><button type="button" data-language="np" aria-label="नेपाली">NP</button>';
      group.addEventListener('click', (event) => {
        const button = event.target.closest('button[data-language]');
        if (button) updateContent(button.dataset.language);
      });
      nav.append(group);
    });
  }

